export type Locale = keyof typeof translations;
export type TranslationKey = keyof typeof translations.en;
export type TranslationValues = Record<string, string | number>;

export const DEFAULT_LOCALE: Locale = 'en';
export const LOCALE_COOKIE = 'pixanony-locale';

export function isLocale(value: string | undefined | null): value is Locale {
  return value === 'en' || value === 'ar';
}

export function directionFor(locale: Locale) {
  return locale === 'ar' ? 'rtl' : 'ltr';
}

export function translate(locale: Locale, key: TranslationKey, values?: TranslationValues): string {
  const message = translations[locale][key] ?? translations.en[key];
  if (!values) return message;

  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
    message as string,
  );
}
