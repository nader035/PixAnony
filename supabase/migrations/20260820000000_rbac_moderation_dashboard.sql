returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  artwork_owner_id uuid;
begin
  select a.user_id into artwork_owner_id
  from public.artworks a
  where a.id = new.artwork_id;

  if not found then
    raise exception 'Artwork not found';
  end if;

  if (select auth.uid()) is not null then
    new.reporter_id := (select auth.uid());
