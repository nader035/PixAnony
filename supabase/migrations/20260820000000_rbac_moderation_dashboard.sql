create or replace function public.get_my_access()
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  with current_access as (
    select coalesce(
      (select ur.role from public.user_roles ur where ur.user_id = (select auth.uid())),
      'user'::public.app_role
    ) as role
  )
  select jsonb_build_object(
    'role', current_access.role::text,
    'permissions', coalesce(
      jsonb_agg(rp.permission::text order by rp.permission::text)
        filter (where rp.permission is not null),
      '[]'::jsonb
    )
  )
  from current_access
  left join public.role_permissions rp on rp.role = current_access.role
  group by current_access.role;
$$;

revoke all on function public.get_my_access() from public, anon;
grant execute on function public.get_my_access() to authenticated;

