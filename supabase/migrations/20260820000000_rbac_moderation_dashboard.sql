create or replace function public.review_report(
  target_report_id uuid,
  decision text,
  note text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  acting_user_id uuid := (select auth.uid());
  report_record public.reports%rowtype;
  action_name public.moderation_action;
  next_status public.report_status;
begin
  if acting_user_id is null
    or not public.has_permission('reports.manage') then
    raise exception 'Insufficient permission to manage reports'
      using errcode = '42501';
  end if;

  if note is not null and char_length(btrim(note)) > 2000 then
    raise exception 'Moderation note is too long';
  end if;

  select * into report_record
  from public.reports
  where id = target_report_id
  for update;

  if not found then
    raise exception 'Report not found';
  end if;

  if report_record.status in ('resolved', 'dismissed') then
    raise exception 'Report is already closed';
  end if;

  case decision
    when 'in_review' then
      next_status := 'in_review';
      action_name := 'report_marked_in_review';
    when 'resolved' then
      next_status := 'resolved';
      action_name := 'report_resolved';
    when 'dismissed' then
      next_status := 'dismissed';
      action_name := 'report_dismissed';
    else
      raise exception 'Invalid report decision';
  end case;

  update public.reports
  set status = next_status,
      assigned_to = acting_user_id,
      resolved_by = case when next_status in ('resolved', 'dismissed') then acting_user_id else null end,
      resolution_note = nullif(btrim(note), ''),
      resolved_at = case when next_status in ('resolved', 'dismissed') then now() else null end,
      updated_at = now()
  where id = target_report_id;

  insert into public.moderation_actions (
    actor_id,
    action,
    report_id,
    target_id,
    target_owner_id,
    note
  )
  values (
    acting_user_id,
    action_name,
    target_report_id,
    report_record.target_id,
    report_record.target_owner_id,
    nullif(btrim(note), '')
  );
end;
$$;

revoke all on function public.review_report(uuid, text, text) from public, anon;
grant execute on function public.review_report(uuid, text, text) to authenticated;

create or replace function public.moderate_artwork(
  target_artwork_id uuid,
  linked_report_id uuid default null,
  note text default null
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  acting_user_id uuid := (select auth.uid());
  artwork_owner_id uuid;
  can_manage_all boolean := public.has_permission('platform.manage');
  has_active_report boolean;
begin
  if acting_user_id is null
    or not public.has_permission('artworks.moderate') then
    raise exception 'Insufficient permission to remove artwork'
      using errcode = '42501';
  end if;

  if note is not null and char_length(btrim(note)) > 2000 then
    raise exception 'Moderation note is too long';
  end if;

  select a.user_id into artwork_owner_id
  from public.artworks a
  where a.id = target_artwork_id
  for update;

  if not found then
    return false;
  end if;

  select exists (
    select 1
    from public.reports r
    where r.target_id = target_artwork_id
      and r.status in ('open', 'in_review')
  ) into has_active_report;

  if not can_manage_all and not has_active_report then
    raise exception 'Moderators can remove only reported artwork'
      using errcode = '42501';
  end if;

  if linked_report_id is not null and not exists (
    select 1
    from public.reports r
    where r.id = linked_report_id
      and r.target_id = target_artwork_id
  ) then
    raise exception 'Report does not match the artwork';
  end if;

  update public.reports
  set status = 'resolved',
      assigned_to = coalesce(assigned_to, acting_user_id),
      resolved_by = acting_user_id,
      resolution_note = coalesce(nullif(btrim(note), ''), 'Artwork removed'),
      resolved_at = now(),
      updated_at = now()
  where target_id = target_artwork_id
    and status in ('open', 'in_review');

  insert into public.moderation_actions (
    actor_id,
    action,
    report_id,
    target_id,
    target_owner_id,
    note
  )
  values (
    acting_user_id,
    'artwork_removed',
    linked_report_id,
    target_artwork_id,
    artwork_owner_id,
    coalesce(nullif(btrim(note), ''), 'Artwork removed')
  );

  delete from public.artworks where id = target_artwork_id;
  return true;
end;
$$;

revoke all on function public.moderate_artwork(uuid, uuid, text) from public, anon;
grant execute on function public.moderate_artwork(uuid, uuid, text) to authenticated;

create or replace function public.get_dashboard_stats()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  result jsonb;
begin
  if not public.has_permission('stats.read') then
    raise exception 'Insufficient permission to view platform statistics'
      using errcode = '42501';
  end if;

  result := jsonb_build_object(
    'open_reports', (select count(*) from public.reports where status = 'open'),
    'in_review_reports', (select count(*) from public.reports where status = 'in_review'),
    'resolved_reports', (select count(*) from public.reports where status = 'resolved'),
    'moderation_actions_30d', (
      select count(*)
      from public.moderation_actions
      where created_at >= now() - interval '30 days'
    )
  );

  if public.has_permission('platform.manage') then
    result := result || jsonb_build_object(
      'total_users', (select count(*) from public.profiles),
      'total_artworks', (select count(*) from public.artworks),
      'public_artworks', (select count(*) from public.artworks where visibility = 'public'),
      'total_likes', (select count(*) from public.likes)
    );
  end if;

  return result;
end;
$$;

