create or replace function public.set_user_role(
  target_user_id uuid,
  target_role text
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  acting_user_id uuid := (select auth.uid());
  previous_role public.app_role;
  resolved_role public.app_role;
begin
  if acting_user_id is null
    or not public.has_permission('roles.manage') then
    raise exception 'Insufficient permission to manage roles'
      using errcode = '42501';
  end if;

  if target_user_id = acting_user_id then
    raise exception 'You cannot change your own role'
      using errcode = '42501';
  end if;

  begin
    resolved_role := target_role::public.app_role;
  exception
    when invalid_text_representation then
      raise exception 'Invalid role';
  end;

  select ur.role into previous_role
  from public.user_roles ur
  where ur.user_id = target_user_id
  for update;

  if not found then
    raise exception 'User role record not found';
  end if;

  if previous_role = resolved_role then
    return;
  end if;

  update public.user_roles
  set role = resolved_role,
      assigned_by = acting_user_id,
      updated_at = now()
  where user_id = target_user_id;

  insert into public.role_audit_log (
    actor_id,
    target_user_id,
    previous_role,
    new_role
  )
  values (
    acting_user_id,
    target_user_id,
    previous_role,
    resolved_role
  );
end;
$$;

revoke all on function public.set_user_role(uuid, text) from public, anon;
grant execute on function public.set_user_role(uuid, text) to authenticated;

create or replace function public.get_dashboard_users(
  search_term text default null,
  result_limit integer default 50,
  result_offset integer default 0
)
returns table (
  user_id uuid,
  username text,
  display_name text,
  avatar_url text,
  is_verified boolean,
  created_at timestamptz,
  role text
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.has_permission('users.read') then
    raise exception 'Insufficient permission to view users'
      using errcode = '42501';
  end if;

  return query
  select
    p.id,
    p.username,
    p.display_name,
    p.avatar_url,
    coalesce(p.is_verified, false),
    p.created_at,
    ur.role::text
  from public.profiles p
  join public.user_roles ur on ur.user_id = p.id
  where nullif(btrim(search_term), '') is null
    or p.username ilike '%' || btrim(search_term) || '%'
    or p.display_name ilike '%' || btrim(search_term) || '%'
  order by p.created_at desc
  limit least(greatest(coalesce(result_limit, 50), 1), 100)
  offset greatest(coalesce(result_offset, 0), 0);
end;
$$;

